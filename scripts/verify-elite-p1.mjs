import fs from 'node:fs'
const read=(p)=>fs.readFileSync(p,'utf8')
function assert(ok,msg){if(!ok){console.error(`FAIL: ${msg}`);process.exitCode=1}else console.log(`PASS: ${msg}`)}

const app=read('src/App.tsx')
const layout=read('src/components/Layout.tsx')
const mine=read('src/pages/MisSolicitudes.tsx')
const admin=read('src/pages/SolicitudesPersonalAdmin.tsx')
const wa=read('src/pages/WhatsAppAdmin.tsx')
const personal=read('supabase/migrations/20260824175006_personal_self_service_requests_and_documents.sql')
const waBase=read('supabase/migrations/20260824174008_whatsapp_templates_outbox_and_consent.sql')
const waControls=read('supabase/migrations/20260824175156_whatsapp_admin_controls_and_retry.sql')
const waFn=read('supabase/functions/procesar-whatsapp-outbox/index.ts')
const anon=read('supabase/migrations/20260824175906_revoke_new_anon_surface_and_postgres_defaults.sql')

assert(app.includes('path="mis-solicitudes" element={<MisSolicitudes />}'),'Autoservicio de personal tiene ruta autenticada')
assert(app.includes('path="whatsapp" element={<AdminRoute><WhatsAppAdmin /></AdminRoute>}'),'WhatsApp está protegido por AdminRoute')
assert(app.includes('path="solicitudes-personal" element={<AdminRoute><SolicitudesPersonalAdmin /></AdminRoute>}'),'Resolución de solicitudes está protegida por AdminRoute')
assert(layout.includes("to: '/mis-solicitudes'"),'Todo el personal ve Mis solicitudes')
assert(layout.includes("to:'/whatsapp'"),'Administración tiene entrada WhatsApp')
assert(layout.includes("to:'/solicitudes-personal'"),'Administración tiene entrada Solicitudes de personal')

assert(mine.includes("rpc('crear_solicitud_personal'"),'Trabajador crea solicitudes mediante RPC')
assert(mine.includes("rpc('cancelar_mi_solicitud_personal'"),'Trabajador cancela su solicitud mediante RPC')
assert(mine.includes("storage.from('personal-documentos')"),'Adjuntos usan bucket privado de personal')
assert(mine.includes("rpc('registrar_documento_personal'"),'Metadatos de documentos se registran por RPC')
assert(!mine.includes("from('personal_permisos').insert"),'Autoservicio no crea permisos operativos directamente')
assert(!mine.includes("from('staff_turno_excepciones').insert"),'Autoservicio no crea excepciones de turno directamente')
assert(admin.includes("rpc('solicitudes_personal_admin'"),'Administración lista solicitudes mediante RPC')
assert(admin.includes("rpc('resolver_solicitud_personal_admin'"),'Administración resuelve solicitudes mediante RPC')
assert(personal.includes("values(req.staff_id,req.tipo,req.fecha_desde,req.fecha_hasta,'Solicitud aprobada:"),'Aprobación materializa permisos en backend')
assert(personal.includes("insert into public.staff_turno_excepciones"),'Aprobación materializa cambio de turno en backend')
assert(personal.includes("values('personal-documentos','personal-documentos',false"),'Bucket de personal se crea privado')
assert(personal.includes("split_part(name,'/',1)=private.auth_staff_id()::text"),'Storage limita al trabajador a su carpeta')

assert(wa.includes("rpc('whatsapp_plantillas_admin'"),'WhatsApp consulta plantillas por RPC')
assert(wa.includes("rpc('guardar_plantilla_whatsapp_admin'"),'WhatsApp guarda plantillas por RPC')
assert(wa.includes("rpc('encolar_whatsapp_admin'"),'WhatsApp encola por RPC con consentimiento')
assert(wa.includes("rpc('reintentar_whatsapp_admin'"),'WhatsApp reintenta por RPC')
assert(wa.includes("rpc('cancelar_whatsapp_admin'"),'WhatsApp cancela por RPC')
assert(wa.includes("functions.invoke('procesar-whatsapp-outbox'"),'UI invoca procesador servidor de outbox')
assert(!wa.includes("from('whatsapp_envios').update"),'UI no modifica outbox directamente')
assert(waBase.includes("consentimiento_whatsapp,false"),'Backend exige consentimiento WhatsApp')
assert(waBase.includes('event_key text not null unique'),'Outbox es idempotente por event_key')
assert(waControls.includes('reintentar_whatsapp_admin'),'Migración contiene control de reintento')
assert(waControls.includes('cancelar_whatsapp_admin'),'Migración contiene control de cancelación')
assert(waFn.includes('staff.rol !== "administrador"'),'Procesador valida administrador en servidor')
assert(waFn.includes('type: "template"'),'Procesador envía únicamente plantillas Meta')
assert(waFn.includes('meta_template_name'),'Procesador exige nombre de plantilla Meta')
assert(!waFn.includes('type: "text",\n        text:'),'Procesador no envía texto libre a Meta')

assert(anon.includes('revoke all privileges on table public.personal_documentos'),'Nuevas tablas de personal revocan anon')
assert(anon.includes('public.whatsapp_envios'),'Nuevas tablas de WhatsApp revocan anon')
assert(anon.includes('alter default privileges for role postgres in schema public revoke all on tables from anon'),'Futuras tablas creadas por postgres no heredan anon')
assert(anon.includes('revoke execute on functions from anon'),'Futuras funciones creadas por postgres no heredan EXECUTE anon')

if(process.exitCode)process.exit(process.exitCode)
console.log('Elite P1 regression checks passed.')
